#!/usr/bin/env bash
# Creates the repo-local SoftHSM2 token store (./data/softhsm) and initialises
# the project's tokens. Idempotent: existing tokens are left untouched.
# PINs are DEV-ONLY defaults (see .env.example); never use them for anything real.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SOFTHSM_DIR="$ROOT/data/softhsm"
TOKEN_DIR="$SOFTHSM_DIR/tokens"
CONF="$SOFTHSM_DIR/softhsm2.conf"
SO_PIN="${QV_HSM_SO_PIN:-so-dev-1234}"
USER_PIN="${QV_HSM_PIN:-user-dev-1234}"
TOKENS=(quorumvault qv-party-1 qv-party-2 qv-party-3 qv-cold)

command -v softhsm2-util >/dev/null || {
  echo "softhsm2-util not found: brew install softhsm (macOS) or apt-get install softhsm2 (Ubuntu)" >&2
  exit 1
}

mkdir -p "$TOKEN_DIR"
cat >"$CONF" <<CONF
# Generated by scripts/setup-softhsm.sh — repo-local, dev only.
directories.tokendir = $TOKEN_DIR
objectstore.backend = file
log.level = INFO
CONF
export SOFTHSM2_CONF="$CONF"

existing_labels() {
  softhsm2-util --show-slots | sed -n 's/^[[:space:]]*Label:[[:space:]]*//p' | sed 's/[[:space:]]*$//'
}

labels="$(existing_labels)"
for label in "${TOKENS[@]}"; do
  if grep -qxF "$label" <<<"$labels"; then
    echo "token '$label' exists, skipping"
  else
    echo "initialising token '$label'"
    softhsm2-util --init-token --free --label "$label" --so-pin "$SO_PIN" --pin "$USER_PIN" >/dev/null
  fi
done

echo
echo "SOFTHSM2_CONF=$CONF"
softhsm2-util --show-slots | grep -E '^Slot |Label:|Serial number:' | grep -v '^$' || true

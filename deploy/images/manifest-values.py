#!/usr/bin/env python3
"""Turns a release manifest (release-<version>.json, written by publish.sh) into the `images:` values of the Helm charts, so nobody copies a digest by hand.

  manifest-values.py release-v1.2.3.json --chart qv-business            > images-qv-business.yaml
  manifest-values.py release-v1.2.3.json --all --out-dir values/        writes values/images-<chart>.yaml for every chart
  manifest-values.py release-v1.2.3.json --all --out-dir v/ --registry registry.internal/qv      mirror: same digests, another repository prefix

Use the files with `helm ... -f images-<chart>.yaml` (last, so they win over the chart's all-zero placeholders). Charts: qv-business, qv-party,
qv-signing-core. (qv-certs runs no image. The Grafana Alloy image `images.agent` of qv-signing-core is not ours: pin it yourself.)

Refuses: a dry-run manifest, a release candidate (unless --allow-rc, for a staging cluster), an image missing from the manifest, a digest that is not
sha256:<64 hex> or is all zeros, and a repository that is not the manifest's own unless --registry names the mirror. Needs only python3.
"""
import argparse, json, os, re, sys

# chart -> values key -> image name (deploy/images/images.sh). One place that says which image a chart value runs.
CHARTS = {
    "qv-business": {"core": "qv-core", "worker": "qv-worker", "relay": "qv-relay", "archiver": "qv-anchor-archiver",
                    "migrate": "qv-migrate", "approval": "qv-approval-web"},
    "qv-party": {"party": "mpc-party", "cosigner": "qv-cosigner"},
    "qv-signing-core": {"gateway": "qv-gateway", "tools": "qv-tools-signing"},
}
DIGEST = re.compile(r"^sha256:[0-9a-f]{64}$")
VERSION = re.compile(r"^v(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)(-rc\.[1-9][0-9]*)?$")


def die(msg):
    print("manifest-values: " + msg, file=sys.stderr)
    sys.exit(1)


def load(path, allow_rc):
    try:
        m = json.load(open(path))
    except (OSError, ValueError) as e:
        die("cannot read %s: %s" % (path, e))
    if m.get("schema") != 1:
        die("unknown manifest schema %r" % m.get("schema"))
    if m.get("dryRun"):
        die("this manifest comes from a dry run: nothing was pushed, its digests name no published image")
    v = m.get("version", "")
    if not VERSION.match(v):
        die("manifest version %r is not vMAJOR.MINOR.PATCH[-rc.N]" % v)
    if "-rc." in v and not allow_rc:
        die("%s is a release candidate: it is for staging; pass --allow-rc to use it anyway" % v)
    return m


def render(m, chart, registry):
    lines = ["# Generated by deploy/images/manifest-values.py from release %s (commit %s). Do not edit: change the release instead." %
             (m["version"], m["source"]["commit"][:12]), "images:"]
    for key, name in CHARTS[chart].items():
        im = m.get("images", {}).get(name)
        if im is None:
            die("the manifest has no image %s (needed by %s images.%s)" % (name, chart, key))
        d = im.get("digest", "")
        if not DIGEST.match(d) or set(d[len("sha256:"):]) == {"0"}:
            die("image %s: digest %r is not a real sha256 digest" % (name, d))
        repo = im["repository"]
        if registry:
            repo = registry.rstrip("/") + "/" + name
        lines.append('  %s: { repository: %s, digest: "%s", tag: "" }' % (key, repo, d))
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("manifest")
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--chart", choices=sorted(CHARTS))
    g.add_argument("--all", action="store_true")
    ap.add_argument("--out-dir", help="with --all: where the files go (created)")
    ap.add_argument("--registry", help="mirror prefix: repository becomes <prefix>/<image name>; digests are unchanged")
    ap.add_argument("--allow-rc", action="store_true")
    a = ap.parse_args()
    m = load(a.manifest, a.allow_rc)
    if a.all:
        if not a.out_dir:
            die("--all needs --out-dir")
        os.makedirs(a.out_dir, exist_ok=True)
        for c in sorted(CHARTS):
            p = os.path.join(a.out_dir, "images-%s.yaml" % c)
            open(p, "w").write(render(m, c, a.registry))
            print(p)
    else:
        sys.stdout.write(render(m, a.chart, a.registry))


main()
